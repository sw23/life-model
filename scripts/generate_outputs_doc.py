"""Generate docs/outputs.md, the glossary of every output life-model produces.

The glossary is rendered from the code: ``LifeModel.STATS`` / ``EXTRA_STATS`` (titles, owners,
aggregation, descriptions), the agent-frame columns, the :class:`~life_model.tax.return_record.TaxReturn`
fields, the ledger's entry fields and flow kinds, and the event kinds. Run it after changing any of
them; ``test_outputs_doc`` fails while the committed file is stale.

Usage (from the repo root)::

    python scripts/generate_outputs_doc.py            # rewrite docs/outputs.md
    python scripts/generate_outputs_doc.py --check    # exit 1 if docs/outputs.md is stale
"""

import argparse
import importlib
import pkgutil
import sys
import types
import typing
from dataclasses import fields
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "outputs.md"


def _import_all_modules() -> None:
    """Import every life_model module so every agent class (and its STATS_OWNED) is registered."""
    import life_model

    for module in pkgutil.walk_packages(life_model.__path__, "life_model."):
        if ".tests" in module.name or module.name.endswith("__main__"):
            continue
        importlib.import_module(module.name)


def _owners(stat_name: str) -> list[str]:
    """The agent classes that declare ``stat_name`` (the most general class of each lineage)."""
    from life_model.model import LifeModelAgent

    classes = []
    pending = list(LifeModelAgent.__subclasses__())
    while pending:
        cls = pending.pop()
        pending.extend(cls.__subclasses__())
        if stat_name in cls.STATS_OWNED and not cls.__module__.startswith(("life_model.tests", "dashboard")):
            classes.append(cls)
    general = [cls for cls in classes if not any(other is not cls and issubclass(cls, other) for other in classes)]
    return sorted({cls.__name__ for cls in general})


def _escape(text: str) -> str:
    return text.replace("|", "\\|")


def _type_text(annotation: object) -> str:
    """Name a dataclass field's type the same way on every supported Python.

    ``getattr(type, "__name__")`` is not portable: Python 3.14 merged ``X | None`` into
    ``typing.Union``, whose ``__name__`` is ``"Union"``, while 3.12/3.13 have no ``__name__`` on it.
    Unions are therefore spelled out from their arms; other types use their short name.
    """
    if isinstance(annotation, str):
        return annotation
    if annotation is type(None):
        return "None"
    if typing.get_origin(annotation) in (typing.Union, types.UnionType):
        return " | ".join(_type_text(arm) for arm in typing.get_args(annotation))
    return getattr(annotation, "__name__", str(annotation))


def render() -> str:
    _import_all_modules()
    from life_model.ledger import FLOW_KIND_DOCS, LEDGER_COLUMNS, LedgerEntry
    from life_model.model import EVENT_COLUMNS, EVENT_KIND_DOCS, EventKind, LifeModel, MoneyStat
    from life_model.results import BALANCE_SHEET_COLUMNS, MONTHLY_BALANCE_SHEET_COLUMNS
    from life_model.tax.return_record import FIELD_DOCS, TaxReturn

    out = [
        "# Outputs glossary",
        "",
        "<!-- Generated by scripts/generate_outputs_doc.py from the code; do not edit by hand. -->",
        "",
        "Everything a run produces, column by column. `LifeModel.run()` returns a `RunResult`",
        "(`life_model.results`) holding all of it: `model_frame`, `agent_frame`, `tax_returns`, `ledger`,",
        "`events`, `balance_sheets`, `monthly_balance_sheets`, `monthly_frame`, `seed`, `spec`; `to_json` /",
        "`to_csv` / `to_parquet` / `load`, `real_dollars()` (money in start-year dollars) and",
        "`explain(year)`. Money is nominal dollars unless a result is `real`; rates are percents.",
        "",
        "The engine steps one month at a time (`LifeModel.step()`); a year is the reporting cadence.",
        "Rows are collected at each year end (December), after the year's taxes are settled.",
        "",
        "## Model frame (one row per year)",
        "",
        "`model.datacollector.get_model_vars_dataframe()` / `RunResult.model_frame`. Each column aggregates",
        "a stat over the agents that declare it in `STATS_OWNED` (a joint return's tax stats are split",
        "across both spouses, so the model total is the return's). `STATS` are the default columns of",
        "`get_yearly_stat_df`; `EXTRA_STATS` are collected too. A **flow** stat (income, spending, taxes)",
        "accumulates month by month over the year and restarts at 0 each January (an agent removed during",
        "the year, such as a decedent, keeps its flows in that year's total); the others are balances read",
        "at the year end.",
        "",
        "| Column | Attribute | Set | Owners | Aggregate | Money | Flow | Description |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
        "| Year | `year` | | LifeModel | | no | | The simulated year. |",
    ]
    for group, stats in (("STATS", LifeModel.STATS), ("EXTRA_STATS", LifeModel.EXTRA_STATS)):
        for stat in stats:
            out.append(
                f"| {stat.title} | `{stat.name}` | {group} | {', '.join(_owners(stat.name))} | "
                f"{stat.aggregator.__name__} | {'yes' if isinstance(stat, MoneyStat) else 'no'} | "
                f"{'yes' if stat.flow else ''} | {_escape(stat.description)} |"
            )
    out += [
        "",
        '## Monthly frame (one row per month, `collect="month"`)',
        "",
        '`LifeModel(collect="month")` (`life_model.run(spec, collect="month")`, `life-model run --collect',
        "month`): `model.monthly_frame()` / `RunResult.monthly_frame` (None otherwise). The model frame's",
        "columns plus `Year` and `Month`, read at each month end: balances as of the month end, flows year",
        "to date (so each December row equals the year's model-frame row).",
    ]

    out += [
        "",
        "## Agent frame (one row per agent per year)",
        "",
        "`model.datacollector.get_agent_vars_dataframe()` (indexed by `Step`, `AgentID`) /",
        "`RunResult.agent_frame` (the same rows with `Year`, `Step` and `AgentID` columns). Every model",
        "stat above is also an agent column (None for agents that do not own it), plus:",
        "",
        "| Column | Description |",
        "| --- | --- |",
        (
            "| Name | The agent's own name: a person's or child's name, a home's name, a job's or account's"
            " company, a fund's or card's name. |"
        ),
        "| Type | The agent's class (`Person`, `BankAccount`, `Job401kAccount`, ...). |",
        "| Owner | The name of the person the agent belongs to (a person's own name). |",
        "| Salary | This year's base salary (`Salary` rows), read before the year-end raise. |",
        "| Spending Base | This year's base spending (`Spending` rows), read before the year-end increase. |",
        "",
        "`model.add_agent_stat(title, attr, pre_post=True)` adds a column read before the year-end",
        "escalators the same way.",
        "",
        "## Tax returns",
        "",
        "`model.tax_returns[(year, unit_id)]` (or `[year]` when the year has one return; `.for_year(year)`),",
        "`person.tax_returns[year]`, `RunResult.tax_returns`: one",
        "`TaxReturn` (`life_model.tax.return_record`) per tax unit per year, built from the numbers the",
        (
            "year was settled with. `total_income - total_adjustments = agi`; `agi - deduction ="
            " taxable_income` (both floored at 0); `ordinary_tax + preferential_tax + niit + amt -"
            " total_credits + total_penalties = federal_tax`; `federal_tax + state_tax + social_security_tax"
            " + medicare_tax = total_tax`, which equals the ledger's tax and penalty outflows for the unit."
        ),
        "",
        "| Field | Type | Description |",
        "| --- | --- | --- |",
    ]
    for field in fields(TaxReturn):
        out.append(f"| `{field.name}` | `{_escape(_type_text(field.type))}` | {_escape(FIELD_DOCS[field.name])} |")

    entry_docs = {
        "seq": "Position in the ledger (0-based, increasing).",
        "year": "Simulated year.",
        "month": "Simulated month (1-12) it was posted in.",
        "stage": (
            "Model stage that posted it (`pre_step`, `events`, `step`, `post_step`, `on_year_start`, `on_year_end`)."
        ),
        "kind": "Flow kind (below).",
        "amount": "Dollars moved (negative only for corrections such as a payroll true-up).",
        "from_account": "Household account the money left (empty for an inflow).",
        "to_account": "Household account the money went to (empty for an outflow).",
        "source": "External counterparty of an inflow.",
        "sink": "External counterparty of an outflow.",
        "cause": "Why it happened.",
        "agent_id": "The person it belongs to (agent `unique_id`).",
        "from_name": "Readable name of `from_account`.",
        "to_name": "Readable name of `to_account`.",
    }
    assert set(entry_docs) == set(LEDGER_COLUMNS), "document every ledger column"
    assert {f.name for f in fields(LedgerEntry)} <= set(LEDGER_COLUMNS)
    out += [
        "",
        "## Cash-flow ledger",
        "",
        "`model.ledger` (`life_model.ledger.CashFlowLedger`); `ledger.to_frame()`, `RunResult.ledger`, and",
        "the DataCollector table `Ledger`. An entry with only `to_account` is an inflow (raises net",
        "worth), one with only `from_account` an outflow, one with both a transfer between household",
        "accounts. Account labels are `<Class>:<unique_id>`, plus `Cash:<person>` (cash held outside",
        "banks) and `Debt:<person>` (unpaid bills carried as debt, a liability).",
        "",
        "| Column | Description |",
        "| --- | --- |",
    ]
    out += [f"| `{column}` | {entry_docs[column]} |" for column in LEDGER_COLUMNS]
    out += ["", "| Kind | Meaning |", "| --- | --- |"]
    out += [f"| `{kind}` | {_escape(doc)} |" for kind, doc in FLOW_KIND_DOCS.items()]

    out += [
        "",
        "## Balance sheets and the conservation check",
        "",
        "`model.balance_sheets[year]` (opening and closing `BalanceSheet`, and the ledger range posted",
        "during the year) / `RunResult.balance_sheets`, and the same per month in",
        "`model.month_balance_sheets[(year, month)]` / `RunResult.monthly_balance_sheets` (with a `month`",
        "column). `life_model.checks` asserts that each year's (with `monthly=True`, each month's) change in",
        "net worth equals the ledger's inflows minus outflows within $1.",
        "",
        "| Column | Description |",
        "| --- | --- |",
        "| `year` | Simulated year. |",
        "| `month` | Simulated month (`monthly_balance_sheets` only). |",
        "| `opening_net_worth` | Household assets minus liabilities before the year's (month's) first stage. |",
        "| `closing_net_worth` | The same after its last stage (December's: the `Net Worth` column). |",
        "| `inflows` | Ledger inflows posted during the year (month). |",
        "| `outflows` | Ledger outflows posted during the year (month). |",
    ]
    assert len(BALANCE_SHEET_COLUMNS) == 5 and len(MONTHLY_BALANCE_SHEET_COLUMNS) == 6

    out += [
        "",
        "## Events",
        "",
        "`model.event_log` (`.list`, `.of_kind`, `.for_year`, `.to_frame()`), `RunResult.events`. The",
        "notebook table (`_repr_html_`) shows the life story; detail kinds are kept but not shown there.",
        "",
        "| Column | Description |",
        "| --- | --- |",
        "| `year` | Year it happened. |",
        "| `month` | Month (1-12) it happened in. |",
        "| `kind` | Event kind (below). |",
        "| `person` / `person_id` | Who it is about. |",
        "| `amount` | Dollars involved, when any. |",
        "| `account` / `account_name` | Account involved (ledger label and readable name). |",
        "| `cause` | Why it happened. |",
        "| `message` | Display text. |",
        "| `details` | Kind-specific extras, as JSON (e.g. a pre-tax withdrawal's `target`). |",
        "",
        "| Kind | Detail | Meaning |",
        "| --- | --- | --- |",
    ]
    assert len(EVENT_COLUMNS) == 11
    for kind in EventKind:
        out.append(f"| `{kind.value}` | {'yes' if kind.is_detail else ''} | {_escape(EVENT_KIND_DOCS[kind.value])} |")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/outputs.md is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"{OUTPUT} is stale: run python scripts/generate_outputs_doc.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
