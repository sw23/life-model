def _import_all_modules() -> None:
    import life_model

    for module in pkgutil.walk_packages(life_model.__path__, "life_model."):
        if ".tests" in module.name or module.name.endswith("__main__") or module.name == "life_model.mcp":
            continue
        importlib.import_module(module.name)


def _class(module: str, name: str):
    return getattr(importlib.import_module(module), name)


def _fmt(value) -> str:
    if value is inspect.Parameter.empty:
        return ""
    if isinstance(value, enum.Enum):
        return f"{type(value).__name__}.{value.name}"
    return repr(value)


def _param(cls, name: str):
    return inspect.signature(cls.__init__).parameters[name]


def _cell(text: str) -> str:
    return " ".join(str(text).replace("|", "\\|").split())


