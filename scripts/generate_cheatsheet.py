def _owner(cls) -> str:
    params = [p for p in inspect.signature(cls.__init__).parameters.values() if p.name != "self"]
    if not params:
        return ""
    first = params[0].name
    return f"`{first}`" if first in ("person", "owner", "job", "family", "model", "beneficiary", "grantor") else ""


def _signature_rows(cls) -> tuple[list[str], list[str]]:
    required, defaults = [], []
    for p in inspect.signature(cls.__init__).parameters.values():
        if p.name == "self" or p.kind in (p.VAR_POSITIONAL, p.VAR_KEYWORD):
            continue
        prefix = "*" if p.kind == p.KEYWORD_ONLY else ""
        if p.default is inspect.Parameter.empty:
            required.append(f"`{prefix}{p.name}`")
        else:
            defaults.append(f"`{prefix}{p.name}={_fmt(p.default)}`")
    return required, defaults


def _spec_rows() -> list[list[str]]:
    from pydantic import BaseModel

    from life_model.spec.docs import _models_in_order

    rows = []
    for model in _models_in_order():
        core = getattr(model, "CORE_CLASS", None)
        if not core or not issubclass(model, BaseModel):
            continue
        required = [f"`{n}`" for n, info in model.model_fields.items() if info.is_required() and n != "kind"]
        defaults = []
        for name, info in model.model_fields.items():
            if info.is_required():
                continue
            default = info.get_default(call_default_factory=True)
            if default is None or default == [] or default == {} or isinstance(default, BaseModel):
                continue
            defaults.append(f"`{name}={default!r}`")
        status = f" (not yet supported: {model.NOT_YET_SUPPORTED})" if getattr(model, "NOT_YET_SUPPORTED", None) else ""
        kind = model.model_fields.get("kind")
        kinds = [a for a in get_args(kind.annotation) if isinstance(a, str)] if kind is not None else []
        label = model.__name__ + (f" (`kind: {kinds[0]}`)" if kinds else "")
        rows.append([label + status, f"`{core}`", ", ".join(required) or "—", ", ".join(defaults) or "—"])
    return rows


def render() -> str:
    _import_all_modules()
    lines = [_INTRO, "## Silent defaults", ""]
    lines.append("| Setting | Default | What it means |")
    lines.append("|---|---|---|")
    for setting, default, meaning in silent_defaults():
        lines.append(f"| {_cell(setting)} | {_cell(default)} | {_cell(meaning)} |")
    lines += [
        "",
        "## Household spec to core",
        "",
        (
            "Each spec entry, the core class the builder constructs, the fields you must give and the spec "
            "defaults you get by leaving the rest out. Full field reference: [household-spec.md](household-spec.md)."
        ),
        "",
        "| Spec model | Builds | Required fields | Defaults when omitted |",
        "|---|---|---|---|",
    ]
    for row in _spec_rows():
        lines.append("| " + " | ".join(_cell(c) for c in row) + " |")
    lines += [
        "",
        "## Core constructors",
        "",
        (
            "The owner argument links the object to its owner (a `Person`, a `Job`, or the `model`); "
            "`*name` marks a keyword-only argument. Rates are percentages (5 = 5%) and `None` defers to the "
            "economy (see above)."
        ),
        "",
        "| Class | Owner | Required | Optional (default) |",
        "|---|---|---|---|",
    ]
    for module, name in CORE_CLASSES:
        cls = _class(module, name)
        required, defaults = _signature_rows(cls)
        row = [f"`{name}` ({module})", _owner(cls), ", ".join(required) or "—", ", ".join(defaults) or "—"]
        lines.append("| " + " | ".join(_cell(c) for c in row) + " |")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} is stale; run python scripts/generate_cheatsheet.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
