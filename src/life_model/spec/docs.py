"""Render ``docs/household-spec.md`` from the schema (``scripts/generate_household_spec_docs.py``).

Every table row comes from the Pydantic field: its type, the ``x-unit`` / ``x-core`` metadata,
its default and its description, so the reference cannot drift from the code (a test regenerates
it and compares).
"""

import types
import typing
from typing import Any, Literal, get_args, get_origin

from pydantic import BaseModel
from pydantic_core import PydanticUndefined

from . import schema as s

_INTRO = """# Household spec reference

<!-- Generated by scripts/generate_household_spec_docs.py from life_model/spec/schema.py; do not edit. -->

A household spec is YAML or JSON describing one household: people, jobs, accounts, debts, housing,
insurance, Social Security, healthcare, giving, children, marriages and dated events.
`life_model.spec.build_model(load(path))` turns it into a `LifeModel`; `spec_from_model(model)`
reads one back; `python -m life_model.spec schema` prints the JSON Schema and
`python -m life_model.spec validate FILE` lists the validator's findings. Synthetic examples ship
in `life_model/spec/examples/` (`life_model.spec.load_example(name)`). Real household files belong
in `my-models/`, which git ignores.

**Conventions.** Every rate ends in `_pct` and is a percentage (4.5 = 4.5%); a value in (0, 1) on
a field marked *typically > 1* warns "did you mean 4.5?". Every flow states its period
(`_annual` or `_monthly`); balances and prices are dollars at the as-of date and never negative
(debts are positive balances). `"economy"` in a growth field follows the simulation economy, so it
varies under stochastic and path economies. Unknown keys are errors.

**Not yet supported.** Fields and kinds marked *not yet supported* are declared so statements can
be written down now; the validator rejects a spec that sets one, naming the plan that adds it.

**Construction order.** The builder never uses the order lists are written in: it sorts each list
(kind, `primary` bank first, then id and content) and builds model, family, people, bank
accounts, jobs, 401ks, stock plans, other accounts, debts, housing, insurance, children, 529s,
healthcare, Social Security, giving, marriages, then events. The head of a married tax unit is the
first spouse listed in `relationships.marriages`; that is a modeling choice, since the household
payment waterfall draws the members' bank accounts in member order.

**Event timing.** `at: {age: A}` resolves through the engine's own `Person.get_year_at_age`
(`start_year + (A - age)`: a person's `age` is their age during the first simulated year). Events
fire in the engine's `events` stage, after the year's income and before the tax units settle the
year, so their effects apply to the year they are dated. An event dated before `start_year` is an
error: put what already happened into the starting state (for example a marriage in
`relationships`).
"""


def _type_name(annotation: Any) -> str:
    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is typing.Annotated:
        inner = args[0]
        if get_origin(inner) in (typing.Union, types.UnionType) and all(
            isinstance(a, type) and issubclass(a, BaseModel) for a in get_args(inner)
        ):
            return "one of: " + ", ".join(_model_link(a) for a in get_args(inner))
        if isinstance(inner, type) and issubclass(inner, BaseModel):
            return _model_link(inner)
        return _type_name(inner)
    if origin in (typing.Union, types.UnionType):
        names = [_type_name(a) for a in args if a is not type(None)]
        text = " \\| ".join(names)
        return f"{text} (optional)" if type(None) in args else text
    if origin is Literal:
        return " \\| ".join(f'`"{a}"`' if isinstance(a, str) else f"`{a}`" for a in args)
    if origin in (list, tuple):
        inner = ", ".join(_type_name(a) for a in args if a is not Ellipsis)
        return f"list[{inner}]"
    if origin is dict:
        return f"map[{_type_name(args[0])} → {_type_name(args[1])}]"
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return _model_link(annotation)
    if annotation is float:
        return "number"
    if annotation is int:
        return "integer"
    if annotation is bool:
        return "boolean"
    if annotation is str:
        return "string"
    return getattr(annotation, "__name__", str(annotation))


def _model_link(model: type[BaseModel]) -> str:
    return f"[{model.__name__}](#{model.__name__.lower()})"


def _default(info) -> str:
    if info.is_required():
        return "**required**"
    default = info.get_default(call_default_factory=True)
    if default is None:
        return "—"
    if isinstance(default, BaseModel):
        return "{}"
    if isinstance(default, (list, dict)) and not default:
        return "[]" if isinstance(default, list) else "{}"
    if isinstance(default, str):
        return f'`"{default}"`'
    if default is PydanticUndefined:
        return "**required**"
    return f"`{default}`"


def _models_in_order() -> list[type[BaseModel]]:
    """Every spec model reachable from HouseholdSpec, in first-reference order."""
    seen: list[type[BaseModel]] = []

    def visit(annotation: Any) -> None:
        if isinstance(annotation, type) and issubclass(annotation, BaseModel):
            if annotation not in seen:
                seen.append(annotation)
                for info in annotation.model_fields.values():
                    visit(info.annotation)
            return
        for arg in get_args(annotation):
            visit(arg)

    visit(s.HouseholdSpec)
    return seen


def _cell(text: str) -> str:
    return " ".join(text.replace("|", "\\|").split())


def child_cost_bands() -> list[tuple[str, str, float, str]]:
    """``(band, ages, start-year dollars a year, note)`` rows of the packaged config's child cost bands (the
    costs a child gets unless ``cost_override_annual`` / ``college_cost_annual`` say otherwise)."""
    from ..config.financial_config import FinancialConfig
    from ..dependents.child import Child

    dep = FinancialConfig().dependents
    childcare_end = Child.CHILDCARE_END_AGE
    college_end = dep.college_start_age + dep.college_years - 1
    return [
        (
            "childcare",
            f"0-{childcare_end - 1}",
            float(dep.childcare_annual_cost),
            "counts as dependent care expenses (credit, dependent-care FSA); replaced by cost_override_annual",
        ),
        (
            "school age",
            f"{childcare_end}-{dep.adult_age - 1}",
            float(dep.school_age_annual_cost),
            "replaced by cost_override_annual",
        ),
        (
            "college",
            f"{dep.college_start_age}-{college_end}",
            float(dep.college_annual_cost),
            "paid from the child's 529 plans first; replaced by college_cost_annual (0: no college)",
        ),
    ]


def _child_bands_section() -> list[str]:
    lines = [
        "### Child cost bands\n",
        "<!-- Generated from the packaged config (dependents in financial_defaults.yaml). -->\n",
        (
            "What a child costs unless the spec says otherwise, in start-year dollars a year, grown with inflation "
            "and charged a twelfth a month by the child's exact age (`birth_month`; January when unset). These "
            "costs come **on top of** the person's `spending.amount_annual`, which excludes modeled child costs: "
            "when the household budget already includes the child, set `cost_override_annual: 0` (and "
            "`college_cost_annual` to the planned amount, 0 for none). The validator warns about every band a "
            "child gets by default.\n"
        ),
        "| Band | Ages | Default cost (USD/year) | Note |",
        "|---|---|---|---|",
    ]
    for band, ages, amount, note in child_cost_bands():
        lines.append(f"| {band} | {ages} | ${amount:,.0f} | {_cell(note)} |")
    lines.append("")
    return lines


#: Generated sections appended after a model's table.
_EXTRA_SECTIONS = {"Child": _child_bands_section}


def render_markdown() -> str:
    """The full ``docs/household-spec.md`` text."""
    lines = [_INTRO]
    lines.append("## Event actions\n")
    lines.append(", ".join(f"`{a}`" for a in s.EVENT_ACTIONS) + ".\n")
    for model in _models_in_order():
        lines.append(f"## {model.__name__}\n")
        doc = " ".join((model.__doc__ or "").split())
        if doc:
            lines.append(doc + "\n")
        core = getattr(model, "CORE_CLASS", None)
        plan = getattr(model, "NOT_YET_SUPPORTED", None)
        if plan:
            lines.append(f"**Not yet supported ({plan}).**\n")
        if core:
            lines.append(f"Builds: `{core}`.\n")
        lines.append("| Field | Type | Unit | Default | Maps to | Description |")
        lines.append("|---|---|---|---|---|---|")
        for name, info in model.model_fields.items():
            extra = info.json_schema_extra if isinstance(info.json_schema_extra, dict) else {}
            unit = str(extra.get(s.UNIT_KEY, ""))
            if extra.get(s.ABOVE_ONE_KEY):
                unit = f"{unit} (typically > 1)"
            core_arg = str(extra.get(s.CORE_KEY, ""))
            description = info.description or ""
            row = [
                f"`{name}`",
                _type_name(info.annotation),
                unit,
                _default(info),
                f"`{core_arg}`" if core_arg else "",
                description,
            ]
            lines.append("| " + " | ".join(_cell(c) for c in row) + " |")
        lines.append("")
        extra_section = _EXTRA_SECTIONS.get(model.__name__)
        if extra_section is not None:
            lines += extra_section()
    return "\n".join(lines).rstrip() + "\n"
